// ── Retrieval ────────────────────────────────────────────────────────────
// Keyword-scoring retrieval: tokenizes the query (Bangla + Latin), scores each
// entry by keyword substring hits and token overlap with content, returns the
// top `limit` matches. Deterministic and dependency-free (no embeddings).

const TOKEN_RE = /[^a-zA-Z0-9\u0980-\u09FF]+/;

function tokenize(text: string): string[] {
  return text
    .toLowerCase()
    .split(TOKEN_RE)
    .map((t) => t.trim())
    .filter((t) => t.length > 0);
}

function scoreEntry(entry: KnowledgeEntry, queryLower: string, queryTokens: string[]): number {
  let score = 0;
  for (const kw of entry.keywords) {
    const k = kw.toLowerCase();
    if (k.length > 1 && queryLower.includes(k)) {
      score += k.length > 3 ? 6 : 3;
    }
  }
  const subjectKey = entry.subject.toLowerCase();
  const subjectTokens = tokenize(entry.subject);
  for (const t of queryTokens) {
    if (entry.keywords.some((kw) => kw.toLowerCase().includes(t) || t.includes(kw.toLowerCase()))) score += 2;
    if (subjectTokens.includes(t)) score += 2;
    if (subjectKey.includes(t)) score += 1;
    if (entry.content.toLowerCase().includes(t)) score += 1;
  }
  return score;
}

/** Retrieve the top `limit` knowledge-base entries most relevant to `query`. */
export function retrieveKnowledge(query: string, limit = 8): KnowledgeEntry[] {
  const queryLower = query.toLowerCase().slice(0, 500);
  const tokens = tokenize(queryLower);
  if (tokens.length === 0) return [];

  const scored = KNOWLEDGE_BASE.map((entry) => ({
    entry,
    score: scoreEntry(entry, queryLower, tokens),
  }))
    .filter((s) => s.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit);

  return scored.map((s) => s.entry);
}